-- 7. documents (Uploaded identification files linked to applications)
create table if not exists public.documents (
  id bigserial primary key,
  application_id uuid,
  doc_type text not null,
  file_path text not null,
  version text not null default 'original',
  created_at timestamptz not null default now()
);

-- 8. screenings (OpenCV, PaddleOCR, field comparison, and Local AI results)
create table if not exists public.screenings (
  id bigserial primary key,
  application_id uuid,
  quality jsonb,
  ocr jsonb,
  comparisons jsonb,
  ai_remark text,
  status text not null default 'completed',
  created_at timestamptz not null default now()
);

-- 9. corrections (Agent-confirmed correction requests and Customer updates)
create table if not exists public.corrections (
  id bigserial primary key,
  application_id uuid,
  agent_id text,
  issue_note text not null,
  customer_response jsonb,
  status text not null default 'Pending Customer',
  created_at timestamptz not null default now()
);

-- 10. notifications (Email and in-app notifications for users)
create table if not exists public.notifications (
  id bigserial primary key,
  user_id text,
  email text,
  role text,
  subject text not null,
  body text not null,
  is_read boolean not null default false,
  created_at timestamptz not null default now()
);

-- 11. system_settings (Admin technical switches: AI enabled/disabled, Maintenance mode)
create table if not exists public.system_settings (
  key text primary key,
  value jsonb not null,
  updated_at timestamptz not null default now()
);

-- 12. system_logs (Technical and operational activity records)
create table if not exists public.system_logs (
  id bigserial primary key,
  actor_email text,
  action text not null,
  detail text,
  created_at timestamptz not null default now()
);

-- ============================================================
-- STORAGE BUCKETS (External Public Assets vs Internal Documents)
-- 1) 'website-assets' (External Public Storage: Banners, Clients, Icons, Permits, Vehicles)
-- 2) 'documents'      (Internal Storage: ids/, corrected-ids/, encoding-proofs/)
-- ============================================================
insert into storage.buckets (id, name, public)
values ('website-assets', 'website-assets', true)
on conflict (id) do update set public = true;

insert into storage.buckets (id, name, public)
values ('documents', 'documents', true)
on conflict (id) do update set public = true;

-- Allow file uploads and reads on both buckets without permission errors
drop policy if exists "Allow public access to website-assets" on storage.objects;
create policy "Allow public access to website-assets"
on storage.objects for all
using (bucket_id = 'website-assets')
with check (bucket_id = 'website-assets');

drop policy if exists "Allow access to documents" on storage.objects;
create policy "Allow access to documents"
on storage.objects for all
using (bucket_id = 'documents')
with check (bucket_id = 'documents');
