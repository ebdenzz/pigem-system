-- 1. users (Customer, Agent, Manager, Admin accounts)
create table if not exists public.users (
  id text primary key,
  email text unique not null,
  full_name text not null,
  role text not null default 'customer',
  active boolean not null default true,
  activated boolean not null default true,
  activation_code text,
  reset_code text,
  avatar_url text,
  intro text,
  created_at timestamptz not null default now()
);
alter table public.users alter column id type text using id::text;
alter table public.users add column if not exists activated boolean not null default true;
alter table public.users add column if not exists activation_code text;
alter table public.users add column if not exists reset_code text;
alter table public.users add column if not exists avatar_url text;
alter table public.users add column if not exists intro text;

-- 2. login_history (Records user login and logout activity)
create table if not exists public.login_history (
  id bigserial primary key,
  user_id text,
  email text,
  role text,
  action text not null default 'login',
  created_at timestamptz not null default now()
);

-- 3. agent_links (Referral links generated by Agents)
create table if not exists public.agent_links (
  id bigserial primary key,
  agent_id text,
  agent_email text,
  agent_name text,
  link_code text unique not null,
  note text,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

-- 4. plans (Internet plans displayed on the public website)
create table if not exists public.plans (
  id text primary key,
  name text not null,
  speed integer not null,
  price numeric not null,
  tag text,
  featured boolean not null default false,
  active boolean not null default true
);

-- 5. website_content (Simple CMS data edited by the Manager: Banners, About, FAQs)
create table if not exists public.website_content (
  key text primary key,
  value jsonb not null,
  updated_at timestamptz not null default now()
